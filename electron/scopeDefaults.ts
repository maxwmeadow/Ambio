import { spawnSync } from 'child_process'
import fs from 'fs'
import { basename, join, normalize, sep } from 'path'
import { classifyProjectFile, isAlwaysSkippedDir } from '../src/shared/fileKinds.ts'

// What a new project's setup leaves out without being told, and why: folders
// tools generated, what each repository's .gitignore says, and folders that
// copy one of the project's repositories. The setup tree shows the reason on
// each row; the scope count skips the same things below what the tree shows.

/**
 * What a generated folder holds, by its usual name. A name alone is not
 * enough: src/components/coverage is often a feature.
 */
const GENERATED_MARKERS: Record<string, { markers: string[]; reason: string }> = {
  coverage: { markers: ['lcov.info', 'coverage-final.json', 'clover.xml', 'lcov-report'], reason: 'Coverage report' },
  obj: { markers: ['project.assets.json'], reason: '.NET build output' },
  bin: { markers: ['Debug', 'Release'], reason: '.NET build output' },
  Library: { markers: ['PackageCache', 'ArtifactDB'], reason: 'Unity cache' },
}

/**
 * The notices code generators put at the top of what they write. archd skips
 * files carrying one (internal/indexer/limits.go, same list).
 */
const GENERATED_HEADER = /Code generated .*DO NOT EDIT|@generated|<auto-generated|Generated by the protocol buffer compiler|Generated by Django|this file (?:is|was) (?:automatically|auto-)generated/i
const GENERATED_HEADER_BYTES = 1024

/** How deep repositories are looked for (archd's RepositoryDepth). */
const REPOSITORY_DEPTH = 4
/** Tracked files of a repository compared against a possible copy of it. */
const COPY_SAMPLE = 40
/** Share of a repository's top-level names a folder must share to be checked as a copy. */
const COPY_NAME_OVERLAP = 0.6
/** Share of sampled files a copy must have at the same paths. */
const COPY_FILE_OVERLAP = 0.75
/** A context is reused while setup recounts on every click. */
const CONTEXT_TTL_MS = 15_000

interface Repository {
  path: string
  name: string
  branch: string
  /** Git's shared folder (`git rev-parse --git-common-dir`), by key: one per repository, whatever its worktrees. */
  commonDir: string
  /** The first commit: two clones of one history share it. */
  rootCommit: string
  /** What Git ignores here, untracked: folders (collapsed) and files, by key. */
  ignored: Set<string>
  /** Top-level names, for spotting a copy. */
  children: Set<string>
  /** Tracked source files, relative, spread across the repository. */
  sample: string[]
}

export interface ProjectContext {
  rootPath: string
  /** Deepest first, so the first match for a path is its own repository. */
  repositories: Repository[]
}

const keyOf = (path: string) => {
  const clean = normalize(path).replace(/[\\/]+$/, '')
  return process.platform === 'win32' ? clean.toLowerCase() : clean
}

function git(cwd: string, args: string[]): string | null {
  const result = spawnSync('git', ['-C', cwd, ...args], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, timeout: 10_000, windowsHide: true })
  return result.status === 0 ? result.stdout : null
}

function readRepository(path: string): Repository {
  const ignored = new Set<string>()
  for (const rel of (git(path, ['ls-files', '-z', '--others', '--ignored', '--exclude-standard', '--directory']) ?? '').split('\0')) {
    if (rel) ignored.add(keyOf(join(path, rel)))
  }
  const tracked = (git(path, ['ls-files', '-z']) ?? '').split('\0')
    .filter(rel => rel && classifyProjectFile(basename(rel)) === 'source')
  const stride = Math.max(1, Math.floor(tracked.length / COPY_SAMPLE))
  const sample = tracked.filter((_, index) => index % stride === 0).slice(0, COPY_SAMPLE)
  let children = new Set<string>()
  try { children = new Set(fs.readdirSync(path).filter(name => name !== '.git')) } catch { /* unreadable */ }
  // "feature/x" (or HEAD when detached), then the shared .git folder.
  const [head = '', commonDir = ''] = (git(path, ['rev-parse', '--abbrev-ref', 'HEAD', '--path-format=absolute', '--git-common-dir']) ?? '').split('\n').map(line => line.trim())
  return {
    path, name: basename(path), ignored, children, sample,
    branch: head === 'HEAD' ? '' : head,
    commonDir: commonDir ? keyOf(commonDir) : '',
    rootCommit: (git(path, ['rev-list', '--max-parents=0', 'HEAD']) ?? '').split('\n')[0].trim(),
  }
}

/** Depth from the project root, then path: the checkout that stays on the Floor. */
const primaryFirst = (left: Repository, right: Repository) =>
  left.path.split(/[\\/]/).length - right.path.split(/[\\/]/).length || left.path.localeCompare(right.path)

/**
 * Another checkout of a repository the project already has: a linked
 * worktree, or a second clone of the same history. The Floor shows one
 * checkout per repository; others are overlays (GIT_AND_PROJECT_SHAPES.md,
 * "One map, many checkouts").
 */
function otherCheckoutReason(context: ProjectContext, dir: string): string | null {
  const own = context.repositories.find(repo => keyOf(repo.path) === keyOf(dir))
  if (!own) return null
  const same = (repo: Repository) => (own.commonDir && repo.commonDir === own.commonDir) || (own.rootCommit && repo.rootCommit === own.rootCommit)
  const primary = context.repositories.filter(same).sort(primaryFirst)[0]
  if (!primary || primary === own) return null
  const branch = own.branch ? ` (${own.branch})` : ''
  return primary.commonDir === own.commonDir ? `Worktree of ${primary.name}${branch}` : `Clone of ${primary.name}${branch}`
}

/** The repositories in a project, and the one around it when it is a folder of one. */
function findRepositories(rootPath: string): string[] {
  const found: string[] = []
  const top = git(rootPath, ['rev-parse', '--show-toplevel'])?.trim()
  if (top) found.push(normalize(top))
  const walk = (dir: string, depth: number) => {
    let entries: fs.Dirent[]
    try { entries = fs.readdirSync(dir, { withFileTypes: true }) } catch { return }
    if (dir !== rootPath && entries.some(entry => entry.name === '.git')) found.push(dir)
    if (depth >= REPOSITORY_DEPTH) return
    for (const entry of entries) {
      if (entry.isDirectory() && !isAlwaysSkippedDir(entry.name)) walk(join(dir, entry.name), depth + 1)
    }
  }
  walk(rootPath, 0)
  return [...new Set(found.map(path => normalize(path)))]
}

const contexts = new Map<string, { at: number; context: ProjectContext }>()

export function projectContext(rootPath: string, now = Date.now()): ProjectContext {
  const cached = contexts.get(rootPath)
  if (cached && now - cached.at < CONTEXT_TTL_MS) return cached.context
  const repositories = findRepositories(rootPath).map(readRepository)
    .sort((left, right) => right.path.length - left.path.length)
  const context = { rootPath, repositories }
  contexts.set(rootPath, { at: now, context })
  return context
}

function repositoryOf(context: ProjectContext, path: string): Repository | undefined {
  const key = keyOf(path)
  return context.repositories.find(repo => key === keyOf(repo.path) || key.startsWith(keyOf(repo.path) + sep))
}

export function isGitIgnored(context: ProjectContext, path: string): boolean {
  return repositoryOf(context, path)?.ignored.has(keyOf(path)) ?? false
}

/** The repository a folder copies: most of its layout and sampled files, at the same paths. */
function copiedRepository(context: ProjectContext, dir: string, names: Set<string>): Repository | undefined {
  if (names.has('.git')) return undefined // a clone or worktree is a checkout, not a copy
  const dirKey = keyOf(dir)
  for (const repo of context.repositories) {
    const repoKey = keyOf(repo.path)
    if (repoKey === dirKey || repoKey.startsWith(dirKey + sep) || repo.children.size < 4 || repo.sample.length < 5) continue
    let shared = 0
    for (const name of repo.children) if (names.has(name)) shared++
    if (shared / new Set([...repo.children, ...names]).size < COPY_NAME_OVERLAP) continue
    const present = repo.sample.filter(rel => fs.existsSync(join(dir, rel))).length
    if (present / repo.sample.length >= COPY_FILE_OVERLAP) return repo
  }
  return undefined
}

/**
 * Why setup leaves a folder out by default, from what it holds, or null.
 * `entries` is the folder's own listing.
 */
export function folderSkipReason(context: ProjectContext, dir: string, entries: fs.Dirent[]): string | null {
  const names = new Set(entries.map(entry => entry.name))
  if (names.has('pyvenv.cfg')) return 'Python virtualenv'
  if (names.has('conda-meta')) return 'Conda environment'
  const generated = GENERATED_MARKERS[basename(dir)]
  if (generated?.markers.some(marker => names.has(marker))) return generated.reason
  if (names.has('.git')) {
    const checkout = otherCheckoutReason(context, dir)
    if (checkout) return checkout
  }
  if (isGitIgnored(context, dir)) return 'In .gitignore'
  const copied = copiedRepository(context, dir, names)
  return copied ? `Copy of ${copied.name}` : null
}

/** Whether a source file starts with a code generator's notice. */
export function hasGeneratedHeader(path: string): boolean {
  let fd: number | undefined
  try {
    fd = fs.openSync(path, 'r')
    const head = Buffer.alloc(GENERATED_HEADER_BYTES)
    const read = fs.readSync(fd, head, 0, GENERATED_HEADER_BYTES, 0)
    return GENERATED_HEADER.test(head.subarray(0, read).toString('utf8'))
  } catch {
    return false
  } finally {
    if (fd !== undefined) fs.closeSync(fd)
  }
}

/** Why setup leaves a file out by default, or null. */
export function fileSkipReason(context: ProjectContext, path: string): string | null {
  if (isGitIgnored(context, path)) return 'In .gitignore'
  if (classifyProjectFile(basename(path)) === 'source' && hasGeneratedHeader(path)) return 'Generated file'
  return null
}

/** Reasons for the entries of one folder in the setup tree, by path. */
export function skipReasons(rootPath: string, dirPath: string): Record<string, string> {
  const context = projectContext(rootPath)
  const reasons: Record<string, string> = {}
  let entries: fs.Dirent[]
  try { entries = fs.readdirSync(dirPath, { withFileTypes: true }) } catch { return reasons }
  for (const entry of entries) {
    const path = join(dirPath, entry.name)
    let reason: string | null = null
    if (entry.isDirectory()) {
      if (isAlwaysSkippedDir(entry.name)) continue
      let inner: fs.Dirent[] = []
      try { inner = fs.readdirSync(path, { withFileTypes: true }) } catch { /* unreadable */ }
      reason = folderSkipReason(context, path, inner)
    } else if (entry.isFile()) {
      reason = fileSkipReason(context, path)
    }
    if (reason) reasons[path] = reason
  }
  return reasons
}

/** For tests: forget cached repositories. */
export function clearProjectContexts(): void {
  contexts.clear()
}
