import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'

import { clearProjectContexts, skipReasons } from './scopeDefaults.ts'
import { estimateScope } from './scopeEstimate.ts'

const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { stdio: 'pipe' })

// A parent folder holding two repositories, the way ThreePillars is laid out:
// a backend with a gitignored folder and file, a linked worktree of it and a
// plain copy of it elsewhere in the project, and generated code.
function project() {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ambio-defaults-')))
  const write = (rel, body = '') => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), body) }
  const api = path.join(root, 'api')
  for (const name of ['routes', 'models', 'services', 'jobs', 'util']) {
    for (let i = 0; i < 2; i++) write(`api/${name}/m${i}.py`, `# ${name} ${i}\n`)
  }
  write('api/.gitignore', 'scratch/\nsettings_local.py\n')
  write('api/scratch/try.py')
  write('api/settings_local.py')
  write('api/pb/user_pb2.py', '# Generated by the protocol buffer compiler.  DO NOT EDIT!\n')
  write('web/src/app.ts')
  fs.mkdirSync(path.join(root, 'web', '.git'))
  git(api, 'init', '-q', '-b', 'main')
  git(api, 'add', '.')
  git(api, '-c', 'user.email=a@b', '-c', 'user.name=a', 'commit', '-q', '-m', 'init')
  git(api, 'worktree', 'add', '-q', '-b', 'feature/x', path.join(root, 'scenario', 'api'))
  fs.cpSync(api, path.join(root, 'backup', 'api'), { recursive: true, filter: source => !source.includes(`${path.sep}.git`) })
  return { root, api }
}

test('setup names why it leaves things out: .gitignore, another checkout, a copy, generated code', () => {
  const { root, api } = project()
  clearProjectContexts()
  try {
    assert.deepEqual(skipReasons(root, path.join(root, 'scenario')), { [path.join(root, 'scenario', 'api')]: 'Worktree of api (feature/x)' })
    assert.deepEqual(skipReasons(root, path.join(root, 'backup')), { [path.join(root, 'backup', 'api')]: 'Copy of api' })
    const inside = skipReasons(root, api)
    assert.equal(inside[path.join(api, 'scratch')], 'In .gitignore')
    assert.equal(inside[path.join(api, 'settings_local.py')], 'In .gitignore')
    assert.deepEqual(skipReasons(root, path.join(api, 'pb')), { [path.join(api, 'pb', 'user_pb2.py')]: 'Generated file' })
    assert.deepEqual(skipReasons(root, root), {}, 'the repositories themselves are the project')

    const top = ['api', 'backup', 'scenario', 'web'].map(name => path.join(root, name))
    const fresh = estimateScope(root, [], {}, top)
    assert.equal(fresh.sourceFiles, 11, "api's ten modules and web's app.ts")
    assert.equal(fresh.generatedFiles, 1)
    assert.deepEqual(fresh.skippedFolders, [path.join(api, 'scratch'), path.join(root, 'backup', 'api'), path.join(root, 'scenario', 'api')].sort())
    assert.deepEqual(fresh.skippedFiles, [path.join(api, 'settings_local.py')])

    const kept = estimateScope(root, [], {}, [...top, path.join(root, 'scenario', 'api')])
    assert.equal(kept.sourceFiles, 21, 'a worktree shown checked is read')
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})
