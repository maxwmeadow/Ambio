const tricky = `package shop

import "errors"

type Cart struct{ items map[string]int }

func (c *Cart) Add(sku string, n int) { c.items[sku] += n }

func (Cart) Kind() string { return "cart" }

func total(prices ...int) int { s := 0; for _, p := range prices { s += p }; return s }

func split(s string) (head, tail string) { return s[:1], s[1:] }

func blank(n int) (_ int, err error) { return n, nil }

func pair() (int, error) {
	return 0, errors.New("no")
}

func Map[T any, U any](xs []T, f func(T) U) []U {
	out := make([]U, 0, len(xs))
	for _, x := range xs {
		out = append(out, f(x))
	}
	return out
}

func noop() {}

func label(n int) int {
	if n > 0 {
		goto done
	}
	n = -n
done:
	return n
}
`

func funcLines(t *testing.T, src []byte) map[string]int {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "x.go", src, 0)
	if err != nil {
		t.Fatalf("does not parse: %v\n%s", err, src)
	}
	out := map[string]int{}
	for _, d := range file.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok {
			out[fd.Name.Name] = fset.Position(fd.Pos()).Line
		}
	}
	return out
}

func TestInstrumentKeepsEveryLineAndParses(t *testing.T) {
	out, ok, err := Instrument([]byte(tricky), "/work/shop/cart.go", "example.com/shop/ambiorecgen")
	if err != nil || !ok {
		t.Fatalf("instrumented: ok=%v err=%v", ok, err)
	}
	before, after := funcLines(t, []byte(tricky)), funcLines(t, out)
	for name, line := range before {
		if after[name] != line {
			t.Errorf("%s moved from line %d to %d", name, line, after[name])
		}
	}
	text := string(out)
	for _, want := range []string{
		`func split(s string) (head, tail string) { __ambioT`,
		`func pair() (ambio_r0 int, ambio_r1 error) {`,
		`func total(prices ...int) (ambio_r0 int) {`,
		`__ambioT.AfterRefs(&c, &sku, &n)`,
		`__ambioT.AfterRefs(&prices, &ambio_r0)`,
		`__ambioT.AfterRefs(&n)`, // blank result: results are not captured
		`ambiorec.Register("/work/shop/cart.go", "Add:7", "Kind:9"`,
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in\n%s", want, text)
		}
	}
}

func TestInstrumentLeavesCgoAndGeneratedFilesAlone(t *testing.T) {
	for _, src := range []string{
		"package a\n\nimport \"C\"\n\nfunc f() {}\n",
		"// Code generated by protoc. DO NOT EDIT.\n\npackage a\n\nfunc f() {}\n",
		"package a\n\nvar x = 1\n",
	} {
		if _, ok, _ := Instrument([]byte(src), "/w/a.go", "m/ambiorecgen"); ok {
			t.Errorf("left alone: %q", src)
		}
	}
}

// The whole overlay builds and runs: a real module, go run, evidence out.
func TestOverlayBuildsAndRecords(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("no go toolchain")
	}
	root := t.TempDir()
	write := func(rel, body string) {
		p := filepath.Join(root, rel)
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/shop\n\ngo 1.18\n")
	write("cart.go", tricky)
	write("cmd/app/main.go", "package main\n\nimport \"fmt\"\n\nfunc main() { fmt.Println(double(21)) }\n\nfunc double(n int) int { return n * 2 }\n")
	dir := t.TempDir()
	overlay, n, err := Build(root, dir)
	if err != nil || n != 2 {
		t.Fatalf("overlay %q n=%d err=%v", overlay, n, err)
	}
	evidence := t.TempDir()
	cmd := exec.Command("go", "run", "./cmd/app")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOFLAGS=-overlay="+overlay, "AMBIO_EVIDENCE_DIR="+evidence,
		watchesEnv(filepath.Join(root, "cmd/app/main.go"), "double"))
	out, err := cmd.CombinedOutput()
	if err != nil || strings.TrimSpace(string(out)) != "42" {
		t.Fatalf("run: %v\n%s", err, out)
	}
	files, _ := filepath.Glob(filepath.Join(evidence, "*.json"))
	if len(files) != 1 {
		t.Fatalf("one evidence document: %v", files)
	}
	data, _ := os.ReadFile(files[0])
	for _, want := range []string{`"name":"double"`, `"symbol":"double"`, `"args":"{n: 21}"`, `"returned":"42"`} {
		if !strings.Contains(string(data), want) {
			t.Errorf("evidence lacks %s: %s", want, data)
		}
	}
	if _, err := os.Stat(filepath.Join(root, PackageDir)); !os.IsNotExist(err) {
		t.Errorf("nothing is written into the user's module")
	}
}

// Drift: a cache hands out the same object, someone else changes it between
// calls, and the watched function sees different data for "the same" input.
func TestOverlayReportsDriftBetweenCalls(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("no go toolchain")
	}
	root := t.TempDir()
	must := func(err error) {
		if err != nil {
			t.Fatal(err)
		}
	}
	must(os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/ledger\n\ngo 1.18\n"), 0o644))
	must(os.WriteFile(filepath.Join(root, "main.go"), []byte(`package main

import "fmt"

type Customer struct {
	Name     string
	Discount int
}

var cache = map[string]*Customer{}

func lookup(id string) *Customer {
	if c, ok := cache[id]; ok {
		return c
	}
	c := &Customer{Name: id}
	cache[id] = c
	return c
}

func price(c *Customer, base int) int { return base - c.Discount }

func main() {
	fmt.Println(price(lookup("a"), 100))
	lookup("a").Discount = 30
	fmt.Println(price(lookup("a"), 100))
}
`), 0o644))
	overlay, _, err := Build(root, t.TempDir())
	must(err)
	evidence := t.TempDir()
	cmd := exec.Command("go", "run", ".")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOFLAGS=-overlay="+overlay, "AMBIO_EVIDENCE_DIR="+evidence,
		watchesEnv(filepath.Join(root, "main.go"), "price", "lookup"))
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("run: %v\n%s", err, out)
	}
	files, _ := filepath.Glob(filepath.Join(evidence, "*.json"))
	if len(files) != 1 {
		t.Fatalf("evidence: %v", files)
	}
	data, _ := os.ReadFile(files[0])
	text := string(data)
	// price sees it in its argument; lookup, the cache itself, in what it returns.
	for _, want := range []string{`"drift":[{"calls":1`, `"after":"30","before":"0","key":"Discount"`, `"path":"c"`, `"param":"c"`, `"path":"return"`} {
		if !strings.Contains(text, want) {
			t.Errorf("evidence lacks %s:\n%s", want, text)
		}
	}
}

// A real module's own test suite, under the overlay: the same results, and
// evidence for its code. Run with AMBIO_REAL_GO_MODULE=<module folder>.
func TestRealModuleUnderTheOverlay(t *testing.T) {
	root := os.Getenv("AMBIO_REAL_GO_MODULE")
	if root == "" {
		t.Skip("set AMBIO_REAL_GO_MODULE to a module folder")
	}
	run := func(env ...string) string {
		cmd := exec.Command("go", "test", "-count=1", "./...")
		cmd.Dir = root
		cmd.Env = append(os.Environ(), env...)
		out, err := cmd.CombinedOutput()
		if err != nil && !strings.Contains(string(out), "\nok") && !strings.HasPrefix(string(out), "ok") {
			t.Logf("go test: %v\n%s", err, out)
		}
		var kept []string
		for _, line := range strings.Split(string(out), "\n") {
			if f := strings.Fields(line); len(f) >= 2 && (f[0] == "ok" || f[0] == "FAIL" || f[0] == "---") {
				kept = append(kept, f[0]+" "+f[1])
			}
		}
		return strings.Join(kept, "\n")
	}
	plain := run()
	overlay, files, err := Build(root, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	evidence := t.TempDir()
	recorded := run("GOFLAGS=-overlay="+overlay+" -vet=off", "AMBIO_EVIDENCE_DIR="+evidence, "AMBIO_WATCHES=[]")
	if recorded != plain {
		t.Fatalf("results differ.\nordinary:\n%s\nrecorded:\n%s", plain, recorded)
	}
	docs, _ := filepath.Glob(filepath.Join(evidence, "*.json"))
	t.Logf("%d files instrumented; %d evidence documents; results:\n%s", files, len(docs), plain)
	if len(docs) == 0 {
		t.Fatal("no evidence")
	}
}

// Go names a function's closures by their order (handler.func1, func2). The
// rewrite must not add one, or every closure the user wrote is renamed in
// panics and stack traces.
func TestInstrumentAddsNoClosure(t *testing.T) {
	src := []byte("package p\n\nfunc handler(n int) (int, error) {\n\tf := func() int { return n }\n\treturn f(), nil\n}\n")
	out, ok, err := Instrument(src, "/w/p.go", "example.com/p/ambiorecgen")
	if err != nil || !ok {
		t.Fatalf("instrument: %v %v", ok, err)
	}
	if got := strings.Count(string(out), "func("); got != strings.Count(string(src), "func(") {
		t.Fatalf("a function literal was added:\n%s", out)
	}
}

// watchesEnv is AMBIO_WATCHES for symbols in one file, JSON-encoded: a Windows
// path pasted into the JSON by hand has backslashes that make it invalid, and
// the recorder then watches nothing.
func watchesEnv(absPath string, symbols ...string) string {
	type watch struct {
		AbsPath string `json:"absPath"`
		Symbol  string `json:"symbol"`
	}
	watches := make([]watch, 0, len(symbols))
	for _, symbol := range symbols {
		watches = append(watches, watch{absPath, symbol})
	}
	encoded, err := json.Marshal(watches)
	if err != nil {
		panic(err)
	}
	return "AMBIO_WATCHES=" + string(encoded)
}
