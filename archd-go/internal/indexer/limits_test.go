package indexer

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"ambio.local/archd/internal/db"
)

func TestGeneratedAndOversizedFilesAreNotIndexed(t *testing.T) {
	dir := t.TempDir()
	write := func(name string, size int) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(strings.Repeat("x", size)), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("app.ts", 100)
	write("bundle.ts", MaxSourceFileBytes+1)
	write("vendor.min.js", 100)

	paths, err := collectSourcePaths(db.Root{Path: dir}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(paths) != 1 || filepath.Base(paths[0]) != "app.ts" {
		t.Fatalf("collected %v, want only app.ts", paths)
	}
}

func TestFilesWithAGeneratorsHeaderAreNotIndexed(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"app.go":          "package app\n",
		"api.pb.go":       "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage app\n",
		"user_pb2.py":     "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
		"0001_initial.py": "# Generated by Django 4.2 on 2024-01-01 00:00\n",
		"Schema.cs":       "//------\n// <auto-generated>\n//     This code was generated by a tool.\n",
		"relay.ts":        "/**\n * @generated SignedSource<<abc>>\n */\n",
		"notes.ts":        "// Explains how generated code is handled; written by hand.\n",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	paths, err := collectSourcePaths(db.Root{Path: dir}, nil)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, path := range paths {
		names = append(names, filepath.Base(path))
	}
	sort.Strings(names)
	if strings.Join(names, ",") != "app.go,notes.ts" {
		t.Fatalf("collected %v, want only the hand-written files", names)
	}
	if !skipsFile(filepath.Join(dir, "api.pb.go")) || skipsFile(filepath.Join(dir, "app.go")) {
		t.Fatal("the watcher and batches skip the same files")
	}
}

func TestAnExcludedFileIsNotIndexed(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"app.py", "settings_local.py"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("x = 1\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	paths, err := collectSourcePaths(db.Root{Path: dir}, []string{filepath.Join(dir, "settings_local.py")})
	if err != nil {
		t.Fatal(err)
	}
	if len(paths) != 1 || filepath.Base(paths[0]) != "app.py" {
		t.Fatalf("collected %v, want only app.py", paths)
	}
}
