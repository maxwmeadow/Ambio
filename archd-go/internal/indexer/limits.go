package indexer

import (
	"errors"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
)

// MaxSourceFileBytes is the largest file Ambio parses. Anything bigger is
// almost always generated - a bundle, a vendored amalgamation, a lockfile-like
// data table - and parsing it costs seconds and memory while adding nothing
// a person would call architecture.
const MaxSourceFileBytes = 1 << 20

// tooLargeOrGenerated reports files skipped by size, by the minified-file
// naming convention, or by a generated-file header.
func tooLargeOrGenerated(path string, entry fs.DirEntry) bool {
	name := strings.ToLower(entry.Name())
	if strings.Contains(name, ".min.") {
		return true
	}
	info, err := entry.Info()
	return (err == nil && info.Size() > MaxSourceFileBytes) || hasGeneratedHeader(path)
}

// skipsFile is tooLargeOrGenerated for a path the watcher or a batch names.
func skipsFile(path string) bool {
	return fileTooLarge(path) || strings.Contains(strings.ToLower(filepath.Base(path)), ".min.") || hasGeneratedHeader(path)
}

// generatedHeader matches the notices code generators put at the top of
// what they write: Go's "Code generated ... DO NOT EDIT.", @generated
// (Relay, Rust, Facebook tools), C#'s <auto-generated>, protoc, Django
// migrations. electron/scopeDefaults.ts counts with the same list.
var generatedHeader = regexp.MustCompile(`Code generated .*DO NOT EDIT|@generated|<auto-generated|Generated by the protocol buffer compiler|Generated by Django|(?i:this file (?:is|was) (?:automatically|auto-)generated)`)

// generatedHeaderBytes is how much of a file's start is searched.
const generatedHeaderBytes = 1024

func hasGeneratedHeader(path string) bool {
	file, err := os.Open(path)
	if err != nil {
		return false
	}
	defer file.Close()
	head := make([]byte, generatedHeaderBytes)
	n, _ := io.ReadFull(file, head)
	return generatedHeader.Match(head[:n])
}

func fileTooLarge(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Size() > MaxSourceFileBytes
}

// ErrIndexCancelled is returned by IndexRoot when the user stopped it.
var ErrIndexCancelled = errors.New("indexing cancelled")

var cancelledRoots sync.Map

// CancelIndexing asks a running full index of rootID to stop. Files already
// parsed stay; the root is not marked indexed, so the next open indexes it
// again from scratch.
func CancelIndexing(rootID string) { cancelledRoots.Store(rootID, true) }

func indexingCancelled(rootID string) bool {
	_, cancelled := cancelledRoots.Load(rootID)
	return cancelled
}

func clearCancel(rootID string) { cancelledRoots.Delete(rootID) }
